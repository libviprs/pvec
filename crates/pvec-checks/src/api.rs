//! A textual snapshot of a crate's public API, and the boundary checks built on it.
//!
//! This is deliberately not a type-resolved tool (that needs a nightly rustdoc JSON). It reads the
//! source the way rustfmt lays it out and records every `pub` item, public field, enum variant,
//! trait method and `pub use`, so a change to the public surface shows up as a diff in a committed
//! file and has to be reviewed. It is conservative in the useful direction: a signature that names a
//! serialization or wire type is caught wherever it appears in that text.
//!
//! Conventions it relies on (and the crates follow): items start a line, `#[cfg(test)]` modules sit
//! at the end of a file, and no public item is generated by a macro.

use std::fs;
use std::path::{Path, PathBuf};

/// The API crates, each with the workspace crates it may depend on. Nothing else may appear in its
/// `[dependencies]`: a serialization, file or network crate there is a boundary violation.
pub const API_CRATES: &[(&str, &[&str])] = &[
    ("pvec-capabilities", &[]),
    ("pvec-codec", &["pvec-capabilities", "pvec-entity", "pvec-geometry", "pvec-numeric"]),
    ("pvec-entity", &["pvec-geometry", "pvec-numeric"]),
    ("pvec-geometry", &["pvec-numeric"]),
];

/// Names that must never appear in a public signature or an API crate's manifest.
pub const BANNED_WIRE_NAMES: [&str; 10] = [
    "serde",
    "flatbuffers",
    "prost",
    "hdf5",
    "bincode",
    "rkyv",
    "capnp",
    "bytemuck",
    "Archived",
    "FlatBuffer",
];

/// The banned names found in `text`, in list order.
pub fn banned_wire_names(text: &str) -> Vec<&'static str> {
    BANNED_WIRE_NAMES.iter().copied().filter(|n| text.contains(n)).collect()
}

/// The dependency names in the `[dependencies]` section of a manifest.
pub fn manifest_dependencies(manifest: &str) -> Vec<String> {
    let mut in_deps = false;
    let mut out = Vec::new();
    for line in manifest.lines() {
        let l = line.trim();
        if l.starts_with('[') {
            in_deps = l == "[dependencies]";
            continue;
        }
        if in_deps && !l.is_empty() && !l.starts_with('#') {
            out.push(l.split(['=', '.']).next().unwrap_or("").trim().to_string());
        }
    }
    out
}

/// Every `.rs` file under `dir`, sorted.
pub fn rust_files(dir: &Path) -> Vec<PathBuf> {
    let mut out = Vec::new();
    let Ok(entries) = fs::read_dir(dir) else { return out };
    for e in entries.flatten() {
        let p = e.path();
        if p.is_dir() {
            out.extend(rust_files(&p));
        } else if p.extension().is_some_and(|x| x == "rs") {
            out.push(p);
        }
    }
    out.sort();
    out
}

/// The code of a file with line comments removed and the trailing `#[cfg(test)]` module cut off.
pub fn strip_comments_and_tests(text: &str) -> String {
    let mut out = String::new();
    for line in text.lines() {
        if line.trim() == "#[cfg(test)]" {
            break;
        }
        out.push_str(line.split("//").next().unwrap_or(""));
        out.push('\n');
    }
    out
}

fn indent_of(line: &str) -> usize {
    line.len() - line.trim_start().len()
}

fn squash(s: &str) -> String {
    s.split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
        .replace("( ", "(")
        .replace(", )", ")")
        .replace(",)", ")")
}

#[derive(Debug)]
enum Ctx {
    /// Inside something we do not report: a function body, a private module, a macro.
    Skip,
    /// Inside a public module (flattened) or the file itself.
    Items,
    Struct(String),
    Enum(String),
    Trait(String),
    Impl(String),
}

/// The public API of every file under `src`, one line per item, files in name order.
pub fn public_api_snapshot(src: &Path) -> String {
    let mut out = String::new();
    for f in rust_files(src) {
        let rel = f.strip_prefix(src).unwrap_or(&f).to_string_lossy().replace('\\', "/");
        let text = fs::read_to_string(&f).unwrap_or_default();
        out.push_str(&public_api_snapshot_of_text(&rel, &text));
    }
    out
}

/// The public API items found in one file's text, each line prefixed with `file`.
pub fn public_api_snapshot_of_text(file: &str, text: &str) -> String {
    let lines: Vec<&str> = text.lines().collect();
    let mut out = String::new();
    let mut stack: Vec<(usize, Ctx)> = vec![(0, Ctx::Items)];
    let mut attrs: Vec<String> = Vec::new();
    let mut i = 0;
    while i < lines.len() {
        let raw = lines[i];
        let t = raw.trim();
        if t == "#[cfg(test)]" {
            break;
        }
        if t.is_empty() || t.starts_with("//") {
            i += 1;
            continue;
        }
        let ind = indent_of(raw);
        // Close contexts whose closing brace is this line.
        if t.starts_with('}') {
            if stack.len() > 1 && stack.last().is_some_and(|(ci, _)| *ci == ind) {
                stack.pop();
            }
            attrs.clear();
            i += 1;
            continue;
        }
        let ctx = stack.last().map(|(_, c)| c);
        if matches!(ctx, Some(Ctx::Skip)) {
            // Entering a nested block inside a skipped region has to be balanced too.
            if t.ends_with('{') {
                stack.push((ind, Ctx::Skip));
            }
            i += 1;
            continue;
        }
        if t.starts_with("#[") {
            let a = squash(t);
            if ["#[derive", "#[non_exhaustive", "#[repr", "#[must_use"].iter().any(|p| a.starts_with(p)) {
                attrs.push(a);
            }
            i += 1;
            continue;
        }
        if t.starts_with("#!") {
            i += 1;
            continue;
        }
        // Gather one statement.
        let mut stmt = t.to_string();
        let is_use = t.starts_with("pub use") || t.starts_with("use ");
        let mut depth = bracket_depth(t);
        let mut j = i;
        let ends = |s: &str, d: i32, head_is_fn: bool, in_fields: bool| -> bool {
            if d > 0 {
                return false;
            }
            if is_use {
                return s.ends_with(';');
            }
            s.ends_with('{')
                || s.ends_with(';')
                || (in_fields && s.ends_with(','))
                || (head_is_fn && s.ends_with('}'))
                || s.ends_with("{}")
        };
        let in_fields = matches!(ctx, Some(Ctx::Struct(_) | Ctx::Enum(_)));
        let head_is_fn = stmt.contains("fn ");
        while !ends(&stmt, depth, head_is_fn, in_fields) && j + 1 < lines.len() {
            j += 1;
            let nt = lines[j].trim();
            if nt.starts_with("//") {
                continue;
            }
            stmt.push(' ');
            stmt.push_str(nt);
            depth += bracket_depth(nt);
            if is_use && depth <= 0 && stmt.ends_with(';') {
                break;
            }
        }
        let stmt = squash(&stmt);
        let opens = stmt.ends_with('{');
        let body = stmt.trim_end_matches('{').trim_end_matches(';').trim_end_matches(',').trim().to_string();
        let prefix = if attrs.is_empty() { String::new() } else { format!("{} ", attrs.join(" ")) };
        attrs.clear();
        let is_pub = body.starts_with("pub ") && !body.starts_with("pub(");
        let word =
            |s: &str| body.starts_with(s) || body.strip_prefix("pub ").is_some_and(|r| r.starts_with(s));
        let mut push_ctx: Option<Ctx> = None;
        match ctx.expect("stack is never empty") {
            Ctx::Items => {
                if body.starts_with("macro_rules!") {
                    push_ctx = Some(Ctx::Skip);
                } else if word("mod ") {
                    if is_pub {
                        emit(&mut out, file, &format!("{prefix}{body}"));
                    }
                    if is_pub && opens {
                        push_ctx = Some(Ctx::Items);
                    } else if opens {
                        push_ctx = Some(Ctx::Skip);
                    }
                } else if word("impl") {
                    let name = impl_name(&body);
                    if !body.contains("Sealed") && body.contains(" for ") {
                        emit(&mut out, file, &body);
                    }
                    if opens {
                        push_ctx = Some(if body.contains(" for ") { Ctx::Skip } else { Ctx::Impl(name) });
                    }
                } else if is_pub {
                    let name = item_name(&body);
                    emit(&mut out, file, &format!("{prefix}{}", drop_value(&body)));
                    if opens {
                        push_ctx = Some(if body.starts_with("pub struct") {
                            Ctx::Struct(name)
                        } else if body.starts_with("pub enum") {
                            Ctx::Enum(name)
                        } else if body.starts_with("pub trait") {
                            Ctx::Trait(name)
                        } else {
                            Ctx::Skip
                        });
                    }
                } else if opens {
                    push_ctx = Some(Ctx::Skip);
                }
            }
            Ctx::Struct(name) => {
                if is_pub {
                    let field = body.trim_start_matches("pub ");
                    emit(&mut out, file, &format!("{name}.{field}"));
                }
                if opens {
                    push_ctx = Some(Ctx::Skip);
                }
            }
            Ctx::Enum(name) => {
                if opens {
                    // A struct-like variant: its fields are part of the signature, so they are recorded.
                    let mut fields = Vec::new();
                    let mut k = j + 1;
                    while k < lines.len() && !lines[k].trim().starts_with('}') {
                        let ft = lines[k].trim();
                        if !ft.is_empty() && !ft.starts_with("//") && !ft.starts_with("#[") {
                            fields.push(squash(ft.trim_end_matches(',')));
                        }
                        k += 1;
                    }
                    emit(&mut out, file, &format!("{name}::{body} {{ {} }}", fields.join(", ")));
                    j = k;
                } else {
                    emit(&mut out, file, &format!("{name}::{body}"));
                }
            }
            Ctx::Trait(name) => {
                if let Some(sig) = body.strip_prefix("fn ") {
                    emit(&mut out, file, &format!("{name}::{sig}"));
                } else if body.starts_with("type ") || body.starts_with("const ") {
                    emit(&mut out, file, &format!("{name}::{body}"));
                }
                if opens {
                    push_ctx = Some(Ctx::Skip);
                }
            }
            Ctx::Impl(name) => {
                if is_pub {
                    let rest = body.trim_start_matches("pub ");
                    let rest = drop_value(rest);
                    let rest = rest
                        .strip_prefix("const ")
                        .filter(|r| r.starts_with("fn "))
                        .unwrap_or(rest.as_str())
                        .to_string();
                    let rest = rest.strip_prefix("fn ").map(str::to_string).unwrap_or(rest);
                    emit(&mut out, file, &format!("{name}::{rest}"));
                }
                if opens {
                    push_ctx = Some(Ctx::Skip);
                }
            }
            Ctx::Skip => unreachable!("skipped above"),
        }
        if let Some(c) = push_ctx {
            stack.push((ind, c));
        }
        i = j + 1;
    }
    out
}

fn emit(out: &mut String, file: &str, item: &str) {
    out.push_str(file);
    out.push_str(": ");
    out.push_str(item);
    out.push('\n');
}

/// Net count of opening minus closing `(`, `[` and `{` in a line, ignoring `{` that ends the line
/// (a block opener, handled by the caller).
fn bracket_depth(line: &str) -> i32 {
    let mut d = 0;
    let chars: Vec<char> = line.chars().collect();
    for (k, c) in chars.iter().enumerate() {
        match c {
            '(' | '[' => d += 1,
            ')' | ']' => d -= 1,
            '{' if k + 1 != chars.len() => d += 1,
            '}' if k != 0 => d -= 1,
            _ => {}
        }
    }
    d
}

fn item_name(body: &str) -> String {
    let rest = body.trim_start_matches("pub ");
    let mut words = rest.split_whitespace();
    words.next();
    let name = words.next().unwrap_or("");
    name.split(['<', '(', ':', '{']).next().unwrap_or("").to_string()
}

fn impl_name(body: &str) -> String {
    let mut s = body.trim_start_matches("pub ").trim_start_matches("impl").trim();
    if s.starts_with('<') {
        let mut depth = 0;
        for (k, c) in s.char_indices() {
            match c {
                '<' => depth += 1,
                '>' => {
                    depth -= 1;
                    if depth == 0 {
                        s = s[k + 1..].trim();
                        break;
                    }
                }
                _ => {}
            }
        }
    }
    s.split(" where").next().unwrap_or(s).trim().to_string()
}

/// Constants keep their type but lose their value: the value is not signature.
fn drop_value(body: &str) -> String {
    let is_const =
        body.starts_with("pub const") || body.starts_with("const") || body.starts_with("pub static");
    match body.split_once(" = ") {
        Some((head, _)) if is_const => head.to_string(),
        _ => body.to_string(),
    }
}

/// Markers of an evaluator in a piece of code: a function named `eval` or `derivative`, or the names
/// of the de Boor and de Casteljau recurrences. There is exactly one evaluator in PVec, in
/// `pvec-geometry`; every other crate reaches it through `Curve2d`.
pub fn second_evaluator_markers(code: &str) -> Vec<&'static str> {
    ["fn eval(", "fn derivative(", "fn local_eval", "deboor", "de_boor", "casteljau"]
        .into_iter()
        .filter(|m| code.contains(m))
        .collect()
}
